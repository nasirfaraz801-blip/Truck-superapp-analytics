"""
Step 2: Run every query in sql/product_analysis.sql against data/superapp.db,
print the results and save them to sql/query_results.md.

Run from the project root:  python scripts/02_run_sql.py
"""
import re
import sqlite3
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]
text = (ROOT / "sql" / "product_analysis.sql").read_text()

queries = []
for block in re.split(r"\n(?=-- Q\d\d\.)", text):
    m = re.match(r"-- (Q\d\d\..*)", block)
    if m:
        body = "\n".join(l for l in block.splitlines() if not l.strip().startswith("--"))
        queries.append((m.group(1).strip(), body.strip().rstrip(";")))

lines = ["# SQL Query Results\n", "Generated by `scripts/02_run_sql.py` from `sql/product_analysis.sql` (simulated data).\n"]
with sqlite3.connect(ROOT / "data" / "superapp.db") as con:
    for title, q in queries:
        res = pd.read_sql_query(q, con)
        print(f"\n=== {title} ===\n{res.to_string(index=False)}")
        lines += [f"\n## {title}\n", res.to_markdown(index=False), ""]

(ROOT / "sql" / "query_results.md").write_text("\n".join(lines))
print(f"\nSaved {len(queries)} result tables to sql/query_results.md")
